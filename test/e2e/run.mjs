import assert from "node:assert/strict";
import { mkdir, readFile, readdir, writeFile } from "node:fs/promises";
import { existsSync } from "node:fs";
import { resolve } from "node:path";
import { Workspace, sleep } from "./workspace.mjs";
import { startModel, lastUser } from "./model.mjs";

const root = resolve(".agent/e2e", new Date().toISOString().replaceAll(":", "-"));
await mkdir(`${root}/project`, { recursive: true });
await mkdir(`${root}/config`, { recursive: true });
const model = await startModel();
await writeFile(`${root}/config/models.json`, JSON.stringify({ providers: { "thread-e2e": {
  baseUrl: `http://127.0.0.1:${model.port}/v1`, api: "openai-completions", apiKey: "test-local-only",
  models: ["thread-fixture", "thread-alternate"].map(id => ({ id, name: id, reasoning: false, input: ["text"], contextWindow: 128000, maxTokens: 4096, cost: { input: 0, output: 0, cacheRead: 0, cacheWrite: 0 } })),

} } }));
await writeFile(`${root}/config/settings.json`, JSON.stringify({ defaultProvider: "thread-e2e", defaultModel: "thread-fixture", theme: "dark", quietStartup: true, retry: { enabled: false }, compaction: { enabled: false, keepRecentTokens: 100, reserveTokens: 512 } }));
const workspace = new Workspace(`pi-thread-e2e-${process.pid}`);
const checks = [];
const check = name => { checks.push(name); console.log(`PASS ${name}`); };
try {
  const start = await workspace.start();
  await writeFile(`${root}/workspace-start.json`, JSON.stringify(start, null, 2));
  check("strict headless mode");
  const command = `cd '${root}/project' && PI_CODING_AGENT_DIR='${root}/config' THREAD_E2E_LIFECYCLE='${root}/lifecycle.log' pi --session-dir '${root}/sessions' --no-extensions --no-skills --no-prompt-templates --no-context-files --append-system-prompt SNAPSHOT_INSTRUCTION_MARKER --offline -e builtin:mcp -e builtin:tool-search -e builtin:codemode -e '${resolve("test/e2e/fixture.ts")}' -e '${resolve("src/index.ts")}'`;
  await workspace.terminal(["bash", "-lc", command]);
  await workspace.resize(1850, 1000);
  await workspace.wait("thread-fixture");
  await sleep(750);
  await workspace.submit("Project pi-thread. Remember SHARED_CEDAR_731.");
  await workspace.wait("ACK Project pi-thread.");
  await sleep(400);
  await workspace.key("F7");
  await workspace.wait("Own context");
  check("main session capture and real docked split");
  const requestCount = model.requests.length;
  await workspace.input("unsent-side-draft");
  await workspace.key("F6");
  await workspace.input("unsent-main-draft");
  await workspace.key("F6");
  const drafts = await workspace.read();
  assert.ok(drafts.includes("unsent-side-draft") && drafts.includes("unsent-main-draft"));
  assert.equal(model.requests.length, requestCount);
  await workspace.key("C-u");
  await workspace.key("F6");
  await workspace.key("C-u");
  await workspace.key("F6");
  check("independent unsent drafts survive focus switching without model calls");
  await workspace.submit("Explain the fork");
  await workspace.wait("remain shared.");
  const inherited = model.requests.find(request => lastUser(request) === "Explain the fork");
  assert.ok(JSON.stringify(inherited).includes("SHARED_CEDAR_731"));
  assert.ok(JSON.stringify(inherited).includes("SNAPSHOT_INSTRUCTION_MARKER"));
  assert.deepEqual(inherited.tools, model.requests[0].tools);
  assert.deepEqual(inherited.messages.filter(message => message.role === "system"), model.requests[0].messages.filter(message => message.role === "system"));
  check("side inherits actual main transcript, exact system prompt, and tool declarations");
  await workspace.submit("SIDE_ONLY_SECRET_842");
  await workspace.wait("ACK SIDE_ONLY_SECRET_842");
  await sleep(200);
  await workspace.key("F6");
  await workspace.submit("/fixture-model");
  await workspace.wait("Main switched model");
  await workspace.submit("MAIN_ONLY_MARKER_953");
  await workspace.wait("ACK MAIN_ONLY_MARKER_953");
  await sleep(200);
  const mainOnly = model.requests.find(request => lastUser(request) === "MAIN_ONLY_MARKER_953");
  assert.ok(!JSON.stringify(mainOnly).includes("SIDE_ONLY_SECRET_842"));
  await workspace.key("F6");
  await workspace.submit("side-isolation-check");
  await workspace.wait("ACK side-isolation-check");
  const sideOnly = model.requests.find(request => lastUser(request) === "side-isolation-check");
  assert.ok(!JSON.stringify(sideOnly).includes("MAIN_ONLY_MARKER_953"));
  assert.equal(mainOnly.model, "thread-alternate");
  assert.equal(sideOnly.model, "thread-fixture");
  check("both directions of context isolation and independent model selection verified in requests");
  await workspace.tool("workspace_screenshot", { output_path: `${root}/split.png` });
  await workspace.key("F7");
  await sleep(400);
  assert.ok(!(await workspace.read()).includes("SIDE THREAD"));
  check("panel closes and main layout restores");

  await workspace.key("F7");
  await workspace.wait("Own context");
  await workspace.submit("fresh-fork-check");
  await workspace.wait("ACK fresh-fork-check");
  const fresh = model.requests.find(request => lastUser(request) === "fresh-fork-check");
  assert.ok(JSON.stringify(fresh).includes("MAIN_ONLY_MARKER_953"));
  assert.ok(!JSON.stringify(fresh).includes("SIDE_ONLY_SECRET_842"));
  assert.equal(fresh.model, "thread-alternate");
  check("reopening creates a fresh fork, discarding the old side context");
  await sleep(250);
  await workspace.submit("write-shared");
  await workspace.wait("Successfully wrote to shared.txt");
  await sleep(350);
  assert.equal(await readFile(`${root}/project/shared.txt`, "utf8"), "shared-file-from-side");
  await workspace.key("F6");
  await workspace.submit("read-shared");
  await workspace.wait("Tool result:");
  await sleep(350);
  const readRequest = model.requests.findLast(request => lastUser(request) === "read-shared");
  assert.ok(JSON.stringify(readRequest).includes("shared-file-from-side"));
  assert.ok(!JSON.stringify(readRequest).includes("write-shared"));
  check("real tools share cwd/files but not side tool history");
  await workspace.key("F6");
  await workspace.submit("fixture-echo");
  await workspace.wait("fixture-echo:");
  await sleep(350);
  const echoed = model.requests.findLast(request => lastUser(request) === "fixture-echo");
  assert.ok(JSON.stringify(echoed).includes("SIDE_TOOL_MARKER"));
  check("file-based extension tools execute in the side session");
  await workspace.submit("mcp-echo");
  await workspace.wait("mcp-echo:");
  await sleep(350);
  const mcp = model.requests.findLast(request => lastUser(request) === "mcp-echo");
  assert.ok(JSON.stringify(mcp).includes("SIDE_MCP_MARKER"));
  assert.ok(model.requests.some(request => lastUser(request) === "mcp-echo" && JSON.stringify(request).includes("tool_search")));
  check("deferred MCP discovery, tool activation, and real MCP execution in side");
  await workspace.submit("denied-write");
  await workspace.wait("fixture-policy-denied");
  await sleep(350);
  assert.ok(!existsSync(`${root}/project/protected.txt`));
  check("tool policy hooks remain enforced in side session");

  await workspace.input("\x1b[200~你好 café 🚀\rmultiline-question\x1b[201~", ["Enter"]);
  await workspace.wait("multiline-question");
  await sleep(350);
  assert.ok(model.requests.some(request => lastUser(request).includes("你好 café 🚀\nmultiline-question")));
  check("Unicode and multiline paste reach the side model");
  await workspace.key("PageUp");
  await sleep(150);
  await workspace.key("PageDown");
  await workspace.resize(900, 700);
  assert.ok((await workspace.read()).includes("SIDE THREAD"));
  await workspace.key("F6");
  await sleep(150);
  assert.ok((await workspace.read()).includes("narrow screen"));
  await workspace.resize(1850, 1000);
  check("scrolling, narrow-screen focus fallback, and resize restoration");

  await workspace.submit("slow-main");
  await workspace.wait("slow-main:");
  await workspace.key("F6");
  await workspace.submit("slow-side");
  await workspace.wait("slow-side:");
  await workspace.key("F7");
  await workspace.wait("slow-main-FINISHED", 15_000);
  assert.ok(!(await workspace.read()).includes("SIDE THREAD"));
  check("close during side streaming does not abort main streaming");
  await sleep(250);
  await workspace.submit("slow-main-2");
  await workspace.wait("slow-main-2:");
  await workspace.key("F7");
  await workspace.wait("Wait for the main");
  assert.ok(!(await workspace.read()).includes("SIDE THREAD"));
  await workspace.wait("slow-main-2-FINISHED", 15_000);
  await sleep(350);
  check("opening while main is busy refuses a partial fork");

  await workspace.key("F7");
  await workspace.wait("Own context");
  await workspace.submit("long-tool");
  await workspace.wait("Running bash");
  await workspace.key("F7");
  await sleep(500);
  assert.ok(!existsSync(`${root}/project/late.txt`));
  check("closing aborts an active bash process");

  await workspace.submit("/compact");
  await workspace.wait(/Compacted|compacted|tokens before/);
  await sleep(500);
  await workspace.key("F7");
  await workspace.wait("Own context");
  await workspace.submit("after-compaction-check");
  await workspace.wait("ACK after-compaction-check");
  const compacted = model.requests.find(request => lastUser(request) === "after-compaction-check");
  assert.ok(JSON.stringify(compacted).includes("SHARED_CEDAR_731"));
  check("fork retains compacted context and its system checkpoint");
  await sleep(250);
  await workspace.submit("provider-error");
  await workspace.wait("fixture-provider-error");
  await workspace.key("F7");
  await sleep(250);
  await workspace.key("F7");
  await workspace.wait("Own context");
  await workspace.submit("recovered-side");
  await workspace.wait("ACK recovered-side");
  check("provider errors recover by closing/reopening");
  await sleep(250);
  await workspace.key("F6");
  await workspace.submit("/reload");
  await workspace.wait(/Reloaded|reloaded/);
  assert.ok(!(await workspace.read()).includes("SIDE THREAD"));
  await workspace.key("F7");
  await workspace.wait("Own context");
  await workspace.key("F6");
  await workspace.submit("/new");
  await sleep(750);
  assert.ok(!(await workspace.read()).includes("SIDE THREAD"));
  await workspace.key("F7");
  await workspace.wait("Own context");
  check("reload and new session clean up old panels and allow reopening");
  await workspace.key("F7");
  await sleep(250);
  for (let cycle = 0; cycle < 3; cycle++) {
    await workspace.key("F7");
    await workspace.wait("Own context");
    await workspace.key("F7");
    await sleep(200);
  }
  check("repeated open/close cycles restore normal main layout");
  await workspace.submit("/fixture-dynamic");
  await workspace.wait("Runtime-only tool registered");
  await workspace.key("F7");
  await workspace.wait("Cannot safely reproduce tool fixture_runtime_only");
  assert.ok(!(await workspace.read()).includes("SIDE THREAD"));
  check("unreproducible runtime tools fail closed and restore main layout");
  await workspace.submit("/reload");
  await workspace.wait(/Reloaded|reloaded/);
  await workspace.submit("BRANCH_ROOT_271");
  await workspace.wait("ACK BRANCH_ROOT_271");
  await sleep(250);
  await workspace.submit("ABANDONED_BRANCH_382");
  await workspace.wait("ACK ABANDONED_BRANCH_382");
  await sleep(250);
  await workspace.submit("/fixture-branch");
  await workspace.wait("Branch navigation complete");
  await workspace.submit("ACTIVE_BRANCH_493");
  await workspace.wait("ACK ACTIVE_BRANCH_493");
  await sleep(250);
  await workspace.key("F7");
  await workspace.wait("Own context");
  await workspace.submit("active-branch-check");
  await workspace.wait("ACK active-branch-check");
  const activeBranch = JSON.stringify(model.requests.find(request => lastUser(request) === "active-branch-check"));
  assert.ok(activeBranch.includes("BRANCH_ROOT_271") && activeBranch.includes("ACTIVE_BRANCH_493"));
  assert.ok(!activeBranch.includes("ABANDONED_BRANCH_382"));
  check("fork copies only the active tree path, not abandoned branches");
  await sleep(250);
  await workspace.key("F6");
  await workspace.key("C-d");
  await sleep(750);
  const lifecycle = await readFile(`${root}/lifecycle.log`, "utf8");
  const pids = [...lifecycle.matchAll(/mcp-start (\d+)/g)].map(match => Number(match[1]));
  for (const pid of pids) assert.throws(() => process.kill(pid, 0), { code: "ESRCH" });
  assert.ok(!existsSync(`${root}/project/late.txt`));
  check("shutdown with panel open cleans up all MCP processes; cancelled tools have no late effects");
  const sessionFiles = (await readdir(`${root}/sessions`)).filter(file => file.endsWith(".jsonl"));
  // Two main sessions were used; no ephemeral side sessions may be on disk.
  assert.equal(sessionFiles.length, 2);
  for (const file of sessionFiles) assert.ok(!(await readFile(`${root}/sessions/${file}`, "utf8")).includes("SIDE_ONLY_SECRET_842"));
  check("side threads are never persisted into session files");

  await workspace.terminal(["bash", "-lc", command.replace("pi --session-dir", "pi --tui-mode regular --session-dir")], "regular-mode");
  await workspace.wait("thread-fixture");
  await workspace.submit("/thread");
  await workspace.wait("requires fullscreen mode");
  check("regular mode refuses unsupported layout without corrupting the terminal");
  await workspace.key("C-d");

  await mkdir(`${root}/installed-config`, { recursive: true });
  await writeFile(`${root}/installed-config/models.json`, await readFile(`${root}/config/models.json`));
  await writeFile(`${root}/installed-config/settings.json`, await readFile(`${root}/config/settings.json`));
  const installCommand = `cd '${root}/project' && export PI_CODING_AGENT_DIR='${root}/installed-config'; pi install '${resolve(".")}' && pi --session-dir '${root}/installed-sessions' --no-skills --no-prompt-templates --no-context-files --offline`;
  await workspace.terminal(["bash", "-lc", installCommand], "installed-package");
  await workspace.wait("thread-fixture", 30_000);
  await workspace.submit("installed-package-smoke");
  await workspace.wait("ACK installed-package-smoke");
  await sleep(300);
  await workspace.key("F7");
  await workspace.wait("Own context");
  await workspace.submit("installed-side-smoke");
  await workspace.wait("ACK installed-side-smoke");
  assert.ok(JSON.stringify(model.requests.find(request => lastUser(request) === "installed-side-smoke")).includes("installed-package-smoke"));
  check("clean pi install loads the package automatically and forks successfully");
  await workspace.key("F7");
  await sleep(250);
  await workspace.key("C-d");
} catch (error) {
  await writeFile(`${root}/failure.txt`, String(error.stack ?? error));
  try { await writeFile(`${root}/failure-screen.txt`, await workspace.read()); await workspace.tool("workspace_screenshot", { output_path: `${root}/failure.png` }); } catch {}
  throw error;
} finally {
  await writeFile(`${root}/requests.json`, JSON.stringify(model.requests, null, 2));
  await writeFile(`${root}/checks.json`, JSON.stringify(checks, null, 2));
  await workspace.stop();
  model.close();
  console.log(`Artifacts: ${root}`);
}
